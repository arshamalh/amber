//! Markdown → Typst, for exporting Markdown notes through the same Typst
//! pipeline as Typst notes (ADR 0006). The result is never written into the
//! vault. Unsupported parts (raw HTML) are dropped, matching the preview.

use std::collections::HashMap;

use comrak::nodes::{AstNode, ListType, NodeValue, TableAlignment};
use comrak::{parse_document, Arena};

use crate::markdown;

/// The `mitex` Typst package converts LaTeX maths; pinned like Tinymist.
pub const MITEX: &str = "@preview/mitex:0.2.7";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MathMode {
    /// Render `$...$` with the mitex package (needs it once from the network).
    Mitex,
    /// Show the LaTeX source as code (offline fallback).
    Source,
}

pub struct Options<'a> {
    /// Vault-relative folder of the note, for resolving relative images.
    pub note_dir: &'a str,
    /// Whether `/_shared/amber.typ` exists, to style `[[links]]` like Typst notes.
    pub amber_helpers: bool,
    pub math: MathMode,
    /// Whether a vault-relative file exists (missing images become a note).
    pub exists: &'a dyn Fn(&str) -> bool,
}

pub struct Converted {
    pub source: String,
    /// Vault-relative paths of images the document uses.
    pub images: Vec<String>,
    pub uses_math: bool,
    pub warnings: Vec<String>,
}

pub fn convert(md: &str, opts: &Options) -> Converted {
    let arena = Arena::new();
    let root = parse_document(&arena, md, &markdown::options());
    let mut w = Writer {
        opts,
        images: Vec::new(),
        uses_math: false,
        warnings: Vec::new(),
        footnotes: HashMap::new(),
    };
    // Footnote definitions are inlined where they are referenced.
    for node in root.descendants() {
        if let NodeValue::FootnoteDefinition(def) = &node.data.borrow().value {
            let text = node
                .children()
                .map(|c| w.inlines(c))
                .collect::<Vec<_>>()
                .join(" ");
            w.footnotes.insert(def.name.clone(), text);
        }
    }
    let body = w.blocks(root, "\n\n");

    let mut head = String::from(
        "// Generated by Amber for PDF export. Not saved in your vault.\n\
         #show link: underline\n\
         #show quote.where(block: true): it => block(inset: (left: 10pt), stroke: (left: 2pt + luma(75%)), it.body)\n",
    );
    if opts.amber_helpers {
        head.push_str("#import \"/_shared/amber.typ\": *\n#show: amber\n");
    }
    if w.uses_math && opts.math == MathMode::Mitex {
        head.push_str(&format!("#import \"{MITEX}\": mi, mitex\n"));
    }
    w.warnings.dedup();
    Converted {
        source: format!("{head}\n{body}\n"),
        images: w.images,
        uses_math: w.uses_math,
        warnings: w.warnings,
    }
}

struct Writer<'o, 'a> {
    opts: &'o Options<'a>,
    images: Vec<String>,
    uses_math: bool,
    warnings: Vec<String>,
    footnotes: HashMap<String, String>,
}

impl Writer<'_, '_> {
    fn blocks<'n>(&mut self, parent: &'n AstNode<'n>, sep: &str) -> String {
        parent
            .children()
            .filter_map(|c| self.block(c))
            .filter(|s| !s.trim().is_empty())
            .collect::<Vec<_>>()
            .join(sep)
    }

    fn block<'n>(&mut self, node: &'n AstNode<'n>) -> Option<String> {
        let value = node.data.borrow().value.clone();
        Some(match value {
            NodeValue::Paragraph => self.inlines(node),
            NodeValue::Heading(h) => {
                format!("{} {}", "=".repeat(h.level as usize), self.inlines(node))
            }
            NodeValue::CodeBlock(cb) => {
                let longest = longest_run(&cb.literal, '`');
                let fence = "`".repeat(longest.max(2) + 1);
                let lang: String = cb
                    .info
                    .split_whitespace()
                    .next()
                    .unwrap_or("")
                    .chars()
                    .filter(|c| c.is_alphanumeric() || matches!(c, '-' | '+' | '_'))
                    .collect();
                format!(
                    "{fence}{lang}\n{}\n{fence}",
                    cb.literal.trim_end_matches('\n')
                )
            }
            NodeValue::ThematicBreak => "#line(length: 100%)".into(),
            NodeValue::BlockQuote => {
                format!("#quote(block: true)[\n{}\n]", self.blocks(node, "\n\n"))
            }
            NodeValue::List(list) => {
                let sep = if list.tight { "\n" } else { "\n\n" };
                let mut items = Vec::new();
                for (i, item) in node.children().enumerate() {
                    let marker = match list.list_type {
                        ListType::Bullet => "- ".to_owned(),
                        ListType::Ordered => format!("{}. ", list.start + i),
                    };
                    let task = match &item.data.borrow().value {
                        NodeValue::TaskItem(t) => Some(t.symbol.is_some()),
                        _ => None,
                    };
                    let mut content = self.blocks(item, sep);
                    if let Some(done) = task {
                        // Drawn, because Typst's bundled fonts have no ☐ glyph.
                        let fill = if done { ", fill: luma(35%)" } else { "" };
                        content.insert_str(
                            0,
                            &format!("#box(width: 0.7em, height: 0.7em, stroke: 0.6pt{fill}, baseline: 0.05em); "),
                        );
                    }
                    items.push(format!("{marker}{}", indent(&content, "  ")));
                }
                items.join(sep)
            }
            NodeValue::Table(t) => {
                let aligns: Vec<&str> = t
                    .alignments
                    .iter()
                    .map(|a| match a {
                        TableAlignment::Left => "left",
                        TableAlignment::Center => "center",
                        TableAlignment::Right => "right",
                        TableAlignment::None => "auto",
                    })
                    .collect();
                let mut out = format!(
                    "#table(\n  columns: {},\n  align: ({},),\n",
                    t.num_columns,
                    aligns.join(", ")
                );
                for row in node.children() {
                    let header = matches!(row.data.borrow().value, NodeValue::TableRow(true));
                    let cells: Vec<String> = row
                        .children()
                        .map(|c| format!("[{}]", self.inlines(c)))
                        .collect();
                    if header {
                        out.push_str(&format!("  table.header({}),\n", cells.join(", ")));
                    } else {
                        out.push_str(&format!("  {},\n", cells.join(", ")));
                    }
                }
                out.push(')');
                out
            }
            NodeValue::Math(m) if m.display_math => self.math(&m.literal, true),
            NodeValue::HtmlBlock(_) => {
                self.warnings.push("Raw HTML was left out.".into());
                return None;
            }
            NodeValue::FootnoteDefinition(_) | NodeValue::FrontMatter(_) => return None,
            // Anything else: render its children as blocks.
            _ => self.blocks(node, "\n\n"),
        })
    }

    fn inlines<'n>(&mut self, parent: &'n AstNode<'n>) -> String {
        let mut out = String::new();
        for node in parent.children() {
            let value = node.data.borrow().value.clone();
            match value {
                NodeValue::Text(t) => out.push_str(&escape(&t)),
                NodeValue::SoftBreak => out.push(' '),
                NodeValue::LineBreak => out.push_str("\\\n"),
                NodeValue::Code(c) => {
                    if c.literal.contains('`') || c.literal.is_empty() {
                        out.push_str(&format!("#raw({});", string(&c.literal)));
                    } else {
                        out.push_str(&format!("`{}`", c.literal));
                    }
                }
                NodeValue::Emph => out.push_str(&format!("#emph[{}];", self.inlines(node))),
                NodeValue::Strong => out.push_str(&format!("#strong[{}];", self.inlines(node))),
                NodeValue::Strikethrough => {
                    out.push_str(&format!("#strike[{}];", self.inlines(node)))
                }
                NodeValue::Superscript => out.push_str(&format!("#super[{}];", self.inlines(node))),
                NodeValue::Underline => {
                    out.push_str(&format!("#underline[{}];", self.inlines(node)))
                }
                NodeValue::Link(link) => {
                    let text = self.inlines(node);
                    let url = link.url.trim();
                    if is_external(url) {
                        out.push_str(&format!("#link({})[{text}];", string(url)));
                    } else {
                        // Links to other notes or anchors: keep the text.
                        out.push_str(&format!("#underline[{text}];"));
                    }
                }
                NodeValue::Image(img) => out.push_str(&self.image(&img.url, node)),
                NodeValue::WikiLink(link) => {
                    let label = plain_text(node);
                    if self.opts.amber_helpers {
                        // Same text as in Typst notes; the amber show rule styles it.
                        let target = escape(link.url.trim());
                        if label.trim() == link.url.trim() || label.is_empty() {
                            out.push_str(&format!("[[{target}]]"));
                        } else {
                            out.push_str(&format!("[[{target}|{}]]", escape(&label)));
                        }
                    } else {
                        let shown = if label.is_empty() {
                            link.url.clone()
                        } else {
                            label
                        };
                        out.push_str(&format!("#underline[{}];", escape(&shown)));
                    }
                }
                NodeValue::FootnoteReference(r) => {
                    let text = self.footnotes.get(&r.name).cloned().unwrap_or_default();
                    out.push_str(&format!("#footnote[{text}];"));
                }
                NodeValue::Math(m) => out.push_str(&self.math(&m.literal, m.display_math)),
                NodeValue::HtmlInline(_) => {
                    self.warnings.push("Raw HTML was left out.".into());
                }
                _ => out.push_str(&self.inlines(node)),
            }
        }
        out
    }

    fn math(&mut self, latex: &str, display: bool) -> String {
        self.uses_math = true;
        match (self.opts.math, display) {
            (MathMode::Mitex, false) => format!("#mi({});", string(latex)),
            (MathMode::Mitex, true) => format!("#mitex({});", string(latex)),
            (MathMode::Source, false) => format!("#raw({}, lang: \"latex\");", string(latex)),
            (MathMode::Source, true) => {
                format!("#raw({}, lang: \"latex\", block: true);", string(latex))
            }
        }
    }

    fn image<'n>(&mut self, url: &str, node: &'n AstNode<'n>) -> String {
        let alt = plain_text(node);
        let url = url.trim();
        if is_external(url) {
            self.warnings
                .push(format!("Web image left as a link: {url}"));
            let shown = if alt.is_empty() { url.to_owned() } else { alt };
            return format!("#link({})[{}];", string(url), escape(&shown));
        }
        let decoded = crate::uri::percent_decode(url.split(['?', '#']).next().unwrap_or(""));
        let Some(path) = join(self.opts.note_dir, &decoded) else {
            self.warnings
                .push(format!("Image outside the vault skipped: {url}"));
            return String::new();
        };
        if !(self.opts.exists)(&path) {
            self.warnings.push(format!("Missing image: {path}"));
            return format!("#emph[\\[missing image: {}\\]];", escape(&path));
        }
        self.images.push(path.clone());
        format!(
            "#image({}, alt: {});",
            string(&format!("/{path}")),
            string(&alt)
        )
    }
}

/// Escapes text so Typst shows it literally.
fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut prev_digit = false;
    for c in text.chars() {
        let special = matches!(
            c,
            '\\' | '*'
                | '_'
                | '`'
                | '$'
                | '#'
                | '['
                | ']'
                | '<'
                | '>'
                | '@'
                | '~'
                | '/'
                | '-'
                | '='
                | '+'
        ) || (c == '.' && prev_digit);
        if special {
            out.push('\\');
        }
        out.push(c);
        prev_digit = c.is_ascii_digit();
    }
    out
}

/// A Typst string literal.
fn string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => {}
            '\t' => out.push_str("\\t"),
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

fn plain_text<'n>(node: &'n AstNode<'n>) -> String {
    node.descendants()
        .filter_map(|n| match &n.data.borrow().value {
            NodeValue::Text(t) => Some(t.to_string()),
            NodeValue::Code(c) => Some(c.literal.clone()),
            _ => None,
        })
        .collect()
}

fn indent(text: &str, pad: &str) -> String {
    let mut lines = text.lines();
    let mut out = lines.next().unwrap_or("").to_owned();
    for line in lines {
        out.push('\n');
        if !line.is_empty() {
            out.push_str(pad);
        }
        out.push_str(line);
    }
    out
}

fn longest_run(s: &str, ch: char) -> usize {
    let (mut best, mut cur) = (0, 0);
    for c in s.chars() {
        cur = if c == ch { cur + 1 } else { 0 };
        best = best.max(cur);
    }
    best
}

fn is_external(url: &str) -> bool {
    let lower = url.to_ascii_lowercase();
    ["http://", "https://", "mailto:"]
        .iter()
        .any(|p| lower.starts_with(p))
}

/// Joins a relative path onto a vault folder; `None` if it climbs out.
fn join(dir: &str, rel: &str) -> Option<String> {
    let mut parts: Vec<&str> = if rel.starts_with('/') {
        Vec::new()
    } else {
        dir.split('/').filter(|s| !s.is_empty()).collect()
    };
    for seg in rel.split('/') {
        match seg {
            "" | "." => {}
            ".." => {
                parts.pop()?;
            }
            s => parts.push(s),
        }
    }
    (!parts.is_empty()).then(|| parts.join("/"))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn conv(md: &str) -> Converted {
        let exists = |p: &str| p == "Notes/img/a.png";
        convert(
            md,
            &Options {
                note_dir: "Notes/sub",
                amber_helpers: true,
                math: MathMode::Mitex,
                exists: &exists,
            },
        )
    }

    #[test]
    fn converts_common_blocks() {
        let c = conv("---\ntitle: x\n---\n# Title\n\nSome *em* and **strong**, `code`.\n\n- a\n- b\n  1. one\n  2. two\n\n> quoted\n\n```rust\nfn main() {}\n```\n\n---\n");
        let s = &c.source;
        assert!(s.contains("= Title"), "{s}");
        assert!(
            s.contains("Some #emph[em]; and #strong[strong];, `code`."),
            "{s}"
        );
        assert!(s.contains("- a\n- b\n  1. one\n  2. two"), "{s}");
        assert!(s.contains("#quote(block: true)[\nquoted\n]"), "{s}");
        assert!(s.contains("```rust\nfn main() {}\n```"), "{s}");
        assert!(s.contains("#line(length: 100%)"), "{s}");
        assert!(!s.contains("title: x"), "{s}");
    }

    #[test]
    fn escapes_typst_syntax_in_text() {
        let c = conv("Price: $5 #1 = a_b * c [x] a < b > c @z 3.14 // not a comment");
        assert!(
            c.source.contains(
                r"Price: \$5 \#1 \= a\_b \* c \[x\] a \< b \> c \@z 3\.14 \/\/ not a comment"
            ),
            "{}",
            c.source
        );
    }

    #[test]
    fn links_images_wikilinks_and_math() {
        let c = conv("[web](https://x.org) [[Other note|shown]] [[Plain]] ![alt](../img/a.png) ![gone](nope.png) $x^2$\n\n$$\\frac{a}{b}$$\n");
        let s = &c.source;
        assert!(s.contains("#link(\"https://x.org\")[web];"), "{s}");
        assert!(
            s.contains("[[Other note|shown]]") && s.contains("[[Plain]]"),
            "{s}"
        );
        assert!(
            s.contains("#image(\"/Notes/img/a.png\", alt: \"alt\");"),
            "{s}"
        );
        assert_eq!(c.images, ["Notes/img/a.png"]);
        assert!(
            c.warnings.iter().any(|w| w.contains("Missing image")),
            "{:?}",
            c.warnings
        );
        assert!(
            s.contains("#mi(\"x^2\");") && s.contains("#mitex(\"\\\\frac{a}{b}\");"),
            "{s}"
        );
        assert!(
            s.starts_with("// Generated") && s.contains("#import \"@preview/mitex"),
            "{s}"
        );
    }

    #[test]
    fn tables_tasks_and_footnotes() {
        let c = conv("| a | b |\n|:--|--:|\n| 1 | 2 |\n\n- [ ] todo\n- [x] done\n\nNote[^n].\n\n[^n]: The footnote.\n");
        let s = &c.source;
        assert!(
            s.contains(
                "columns: 2,\n  align: (left, right,),\n  table.header([a], [b]),\n  [1], [2],\n)"
            ),
            "{s}"
        );
        assert!(
            s.contains(
                "- #box(width: 0.7em, height: 0.7em, stroke: 0.6pt, baseline: 0.05em); todo"
            ),
            "{s}"
        );
        assert!(
            s.contains("stroke: 0.6pt, fill: luma(35%), baseline: 0.05em); done"),
            "{s}"
        );
        assert!(s.contains("Note#footnote[The footnote.];."), "{s}");
    }

    #[test]
    fn drops_html_and_handles_paths() {
        let c = conv("<div>x</div>\n\nhi <b>there</b>\n");
        assert!(
            !c.source.contains("<div>") && !c.source.contains("<b>"),
            "{}",
            c.source
        );
        assert!(!c.warnings.is_empty());
        assert_eq!(join("a/b", "../c.png").as_deref(), Some("a/c.png"));
        assert_eq!(join("a", "../../c.png"), None);
        assert_eq!(join("a/b", "/x/y.png").as_deref(), Some("x/y.png"));
    }
}
